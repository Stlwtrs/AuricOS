#!/usr/bin/env bash
# Prepare a signed AuricOS release from a built ISO.
#
# Usage: bash scripts/release.sh <version> [path/to/auricos.iso]
#   <version>  release tag, for example v1.0.0
#   ISO        defaults to the newest ISO in out/
#
# Writes to release/<version>/:
#   SHA256SUMS          checksum of the ISO
#   SHA256SUMS.sig      PGP signature of SHA256SUMS
#   <iso>.sig           PGP signature of the ISO itself
#   release-notes.md    draft notes for the GitHub release (edit before publishing)
#
# The ISO itself is not copied. Run as your normal user, not with sudo,
# so gpg uses your own keyring.

set -euo pipefail

KEY=${AURICOS_SIGNING_KEY:-04544553060CE6C62DA54EE1E013161D5438F94A}
REPO=Stlwtrs/AuricOS
MAX_BYTES=$((2 * 1024 * 1024 * 1024))   # GitHub release files must be under 2 GiB

die()  { printf '\033[31merror:\033[0m %s\n' "$1" >&2; exit 1; }
warn() { printf '\033[33mwarning:\033[0m %s\n' "$1" >&2; }
ok()   { printf '\033[32m  ok\033[0m %s\n' "$1"; }

[ $# -ge 1 ] && [ $# -le 2 ] || die "usage: bash scripts/release.sh <version> [path/to/iso]"
VERSION=$1
[[ $VERSION =~ ^v[0-9]+\.[0-9]+\.[0-9]+(-[A-Za-z0-9.]+)?$ ]] || die "version must look like v1.0.0 or v1.0.0-beta.1"
[ "$EUID" -ne 0 ] || die "don't run this with sudo: your signing key is in your own keyring"
for cmd in git gpg sha256sum stat; do command -v "$cmd" >/dev/null || die "$cmd is not installed"; done

cd "$(git rev-parse --show-toplevel)"

echo "== Checking the ISO"
if [ $# -eq 2 ]; then
    ISO=$2
else
    ISO=$(ls -t out/*.iso 2>/dev/null | head -1) || true
    [ -n "$ISO" ] || die "no ISO found in out/; build one first or pass its path"
    [ "$(ls out/*.iso | wc -l)" -eq 1 ] || warn "several ISOs in out/; using the newest: $ISO"
fi
[ -f "$ISO" ] || die "$ISO does not exist"
NAME=$(basename "$ISO")
SIZE=$(stat -c %s "$ISO")
SIZE_MB=$((SIZE / 1024 / 1024))
[ "$SIZE" -lt "$MAX_BYTES" ] || die "$NAME is ${SIZE_MB} MiB; GitHub release files must be under 2048 MiB"
ok "$NAME (${SIZE_MB} MiB, under GitHub's 2 GiB limit)"

echo "== Checking the source"
[ -z "$(git status --porcelain)" ] || die "uncommitted changes; a release must be built from a committed state"
COMMIT=$(git rev-parse HEAD)
ok "working tree clean at ${COMMIT:0:7}"
if [ "$(stat -c %Y "$ISO")" -lt "$(git log -1 --format=%ct)" ]; then
    die "the ISO is older than the latest commit; rebuild it so it matches the source"
fi
ok "ISO was built after the latest commit"
if git rev-parse -q --verify "refs/tags/$VERSION" >/dev/null; then
    [ "$(git rev-parse "$VERSION^{commit}")" = "$COMMIT" ] || die "tag $VERSION already exists on a different commit"
    ok "tag $VERSION points at this commit"
else
    warn "tag $VERSION doesn't exist yet; create it before publishing (see the next steps below)"
fi

echo "== Checking the signing key"
gpg --list-secret-keys "$KEY" >/dev/null 2>&1 || die "no secret key for $KEY in your keyring"
EXPIRES=$(gpg --with-colons --list-keys "$KEY" | awk -F: '$1=="pub"{print $7; exit}')
if [ -n "$EXPIRES" ]; then
    [ "$EXPIRES" -gt "$(date +%s)" ] || die "signing key $KEY has expired"
    ok "key $KEY (expires $(date -d "@$EXPIRES" +%Y-%m-%d))"
else
    ok "key $KEY (no expiry)"
fi

OUT=release/$VERSION
[ ! -e "$OUT" ] || die "$OUT already exists; remove it to start over"
mkdir -p "$OUT"

echo "== Creating the checksum"
SHA256=$(sha256sum "$ISO" | cut -d' ' -f1)
printf '%s  %s\n' "$SHA256" "$NAME" > "$OUT/SHA256SUMS"
ok "SHA256 $SHA256"

echo "== Signing (gpg may ask for your key's passphrase)"
gpg --local-user "$KEY" --detach-sign --output "$OUT/$NAME.sig" "$ISO"
gpg --local-user "$KEY" --detach-sign --output "$OUT/SHA256SUMS.sig" "$OUT/SHA256SUMS"
gpg --verify "$OUT/$NAME.sig" "$ISO" 2>/dev/null || die "ISO signature failed to verify"
gpg --verify "$OUT/SHA256SUMS.sig" "$OUT/SHA256SUMS" 2>/dev/null || die "SHA256SUMS signature failed to verify"
ok "both signatures verify"

FPR=$(gpg --with-colons --fingerprint "$KEY" | awk -F: '$1=="fpr"{print $10; exit}' | sed 's/.\{4\}/& /g; s/ $//')

cat > "$OUT/release-notes.md" <<EOF
<!-- Draft generated by scripts/release.sh. Edit before publishing. -->

**AuricOS $VERSION:** a security-hardened Arch Linux distribution with an XFCE desktop and the CachyOS BORE kernel.

## Download

| File | Purpose |
|---|---|
| \`$NAME\` | The live ISO (${SIZE_MB} MiB) |
| \`$NAME.sig\` | PGP signature of the ISO |
| \`SHA256SUMS\` and \`SHA256SUMS.sig\` | Checksum and its signature |

SHA256: \`$SHA256\`

**Verify before installing.** See [Verifying a Release](https://github.com/$REPO/blob/main/docs/verifying-releases.md). In short:

\`\`\`bash
sha256sum -c SHA256SUMS
gpg --verify $NAME.sig $NAME
\`\`\`

The signing key's fingerprint is \`$FPR\`.

## Highlights

<!-- Summarize the main features or changes since the last release. See CHANGELOG.md. -->

## Requirements

- 64-bit x86 computer, 4 GB RAM (8 GB recommended), 20 GB disk
- BIOS or UEFI firmware
- **Secure Boot must be turned off.** The bootloader and kernel aren't signed yet.

## Known Limitations

<!-- Update after hardware testing. -->
- Tested in QEMU/KVM on BIOS and UEFI. Physical hardware testing is limited; please report what works and what doesn't.
- Secure Boot is not supported yet.

## Source

Built from commit [\`${COMMIT:0:7}\`](https://github.com/$REPO/commit/$COMMIT). AuricOS's own configuration and packages are in this repository. The bundled software comes from Arch Linux, CachyOS and the AUR; each package's source and license are available from those projects.

Full changes: [CHANGELOG.md](https://github.com/$REPO/blob/$COMMIT/CHANGELOG.md)
EOF
ok "release notes draft written"

cat <<EOF

Release files are in $OUT/:
$(ls -1 "$OUT" | sed 's/^/  /')

Next steps:
  1. Edit $OUT/release-notes.md
  2. Tag and push (if not done yet):
       git tag -u $KEY $VERSION -m "AuricOS $VERSION"
       git push origin $VERSION
  3. Publish (GitHub CLI), or upload the same files at
     https://github.com/$REPO/releases/new
       gh release create $VERSION "$ISO" $OUT/$NAME.sig $OUT/SHA256SUMS $OUT/SHA256SUMS.sig \\
         --title "AuricOS $VERSION" --notes-file $OUT/release-notes.md
EOF
